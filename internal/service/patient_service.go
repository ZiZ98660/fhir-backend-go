package service

import (
	"context"
	"encoding/json"
	"errors"
	"go-fhir-phase1/internal"
	"go-fhir-phase1/internal/repository"
)

// PatientService handles the business logic for Patients.
type PatientService struct {
	repo repository.PatientStore
}

// NewPatientService creates a new service instance.
func NewPatientService(repo repository.PatientStore) *PatientService {
	return &PatientService{repo: repo}
}

// CreatePatient handles the logic of validating and saving a patient.
func (s *PatientService) CreatePatient(ctx context.Context, p internal.Patient) (internal.Patient, error) {
	// FHIR Validation: Check if at least one name is provided and has a family name.
	if len(p.Name) == 0 || p.Name[0].Family == "" {
		return internal.Patient{}, errors.New("at least one name with a family name is required")
	}

	// In a real system, this ID would be generated by a UUID or the DB.
	p.ID = "pt-fhir-123"

	data, err := json.Marshal(p)
	if err != nil {
		return internal.Patient{}, err
	}

	err = s.repo.SavePatient(ctx, p, data)
	if err != nil {
		return internal.Patient{}, err
	}

	return p, nil
}

// SearchPatients retrieves patients and wraps them in a FHIR Bundle.
// This is the "Professional" way to return lists in FHIR.
func (s *PatientService) SearchPatients(ctx context.Context) (internal.Bundle, error) {
	dataList, err := s.repo.GetPatients(ctx)
	if err != nil {
		return internal.Bundle{}, err
	}

	bundle := internal.Bundle{
		ResourceType: "Bundle",
		Type:         "search",
		Total:        len(dataList),
		Entry:        make([]internal.BundleEntry, 0, len(dataList)),
	}

	for _, data := range dataList {
		var p internal.Patient
		if err := json.Unmarshal(data, &p); err != nil {
			continue
		}

		// Wrap the patient in a BundleEntry
		bundle.Entry = append(bundle.Entry, internal.BundleEntry{
			FullUrl:  "http://localhost:8080/api/v1/Patient/" + p.ID,
			Resource: p,
		})
	}

	return bundle, nil
}

// GetPatientByID fetches a specific patient.
func (s *PatientService) GetPatientByID(ctx context.Context, id string) (internal.Patient, error) {
	data, err := s.repo.GetPatientByID(ctx, id)
	if err != nil {
		return internal.Patient{}, err
	}

	var p internal.Patient
	if err := json.Unmarshal(data, &p); err != nil {
		return internal.Patient{}, err
	}

	return p, nil
}

